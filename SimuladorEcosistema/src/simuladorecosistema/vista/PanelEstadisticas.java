// Muestra una fila por turno con la población viva de cada tipo
    public void mostrarHistorial(ArrayList<RegistroPoblacion> historial) {
        Object[][] filas = new Object[historial.size()][];
        for (int i = 0; i < historial.size(); i++) {
            RegistroPoblacion r = historial.get(i);
            filas[i] = new Object[]{r.getTurno(), r.getPlantas(), r.getConejos(), r.getLobos()};
        }
        String[] columnas = {"Turno", "Plantas", "Conejos", "Lobos"};
        tblHistorial.setModel(new DefaultTableModel(filas, columnas) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        });
        if (filas.length > 0) {
            // Deja a la vista el último turno
            tblHistorial.scrollRectToVisible(tblHistorial.getCellRect(filas.length - 1, 0, true));
        }
    }

    public void limpiar() {
        mostrarHistorial(new ArrayList<>());
    }
    
