    // Muestra una de las tres pantallas: CONFIGURACION, SIMULACION o REPORTE.
    // Usa el orden en que se agregaron los paneles al contenedor (configuración, simulación, reporte)
    public void mostrarPantalla(String nombre) {
        java.awt.CardLayout cartas = (java.awt.CardLayout) panelContenedor.getLayout();
        int posicion = java.util.Arrays.asList(CONFIGURACION, SIMULACION, REPORTE).indexOf(nombre);
        cartas.first(panelContenedor);
        for (int i = 0; i < posicion; i++) {
            cartas.next(panelContenedor);
        }
        pantallaActual = nombre;
    }

    // Acciones de navegacion: las usan los botones de arriba (y mas adelante el menu)
    private void irAConfiguracion() {
        mostrarPantalla(CONFIGURACION);
    }

     private void irASimulacion() {
        mostrarPantalla(SIMULACION);
    }

    private void verReporte() {
        controlador.mostrarReporte();
    }

    // Implementación de IVista 

   @Override
    public void mostrarError(String mensaje) {
        if (CONFIGURACION.equals(pantallaActual)) {
            panelConfiguracion.mostrarErrores(mensaje);
        } else {
            JOptionPane.showMessageDialog(this, mensaje, "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }
    
    @Override
    public void mostrarEstado(int turnoActual, int turnosTotales, int plantas, int conejos, int lobos, String clima) {
        lblEstado.setText("Turno " + turnoActual + "/" + turnosTotales + " | Plantas: " + plantas
                + " | Conejos: " + conejos + " | Lobos: " + lobos + " | Clima: " + clima);
        panelSimulacion.actualizarEstado(turnoActual, turnosTotales, plantas, conejos, lobos, clima);
        mostrarPantalla(SIMULACION);
    }

    @Override
    public void mostrarEventos(ArrayList<String> eventos) {
        panelSimulacion.mostrarEventos(eventos);
    }

    @Override
    public void mostrarMensaje(String mensaje) {
        lblEstado.setText(mensaje);
        panelSimulacion.mostrarMensaje(mensaje, false);
    }

    @Override
    public void ofrecerIntervencion(int turnoActual) {
        panelSimulacion.ofrecerIntervencion(turnoActual);
    }

    @Override
    public void mostrarReporte(ReporteFinal reporte) {
        panelReporte.mostrarReporte(reporte);
        mostrarPantalla(REPORTE);
    }

    @Override
    public void mostrarSinSimulacion(String motivo) {
        lblEstado.setText(motivo);
        panelSimulacion.mostrarSinSimulacion(motivo);
        mostrarPantalla(SIMULACION);
    }
   
